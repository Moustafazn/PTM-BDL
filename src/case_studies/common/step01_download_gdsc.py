def find_file(directory: Path, patterns: list[str], description: str) -> Path | None:
    """
    Search for a file matching any of the given patterns (case-insensitive).
    Supports .xlsx, .csv, and .tsv extensions.
    
    Returns the first matching file path, or None if not found.
    """
    all_files = list(directory.iterdir()) if directory.exists() else []

    for f in sorted(all_files):
        fname_lower = f.name.lower()
        # Skip hidden files and temp files
        if fname_lower.startswith(".") or fname_lower.startswith("~"):
            continue
        # Check each pattern
        for pattern in patterns:
            if pattern.lower() in fname_lower:
                print(f"  ✓ Found {description}: {f.name}")
                return f

    return None


def locate_gdsc_files():
    """
    Look for manually downloaded GDSC files in the raw/gdsc/ directory.
    
    We search for files by name patterns since the exact filename depends
    on when the user downloaded from Cell Model Passports (they append dates,
    change formats between releases, etc.).
    
    Returns (dose_response_path, cell_lines_path) — either may be None.
    """
    print("\n" + "=" * 70)
    print("STEP 1.1: Locating GDSC Data Files")
    print("=" * 70)
    print(f"  Looking in: {RAW_DIR}")

    if RAW_DIR.exists():
        files_in_dir = [f.name for f in RAW_DIR.iterdir()
                        if not f.name.startswith(".")]
        print(f"  Files found: {files_in_dir}")
    else:
        print(f"  Directory does not exist yet. Creating...")
        RAW_DIR.mkdir(parents=True, exist_ok=True)

    # ── Search for dose-response file ──────────────────────────────────────
    dose_response_patterns = [
        "gdsc2_dose_response",
        "gdsc2_fitted_dose_response",
        "fitted_dose_response_gdsc2",
        "dose_response_gdsc2",
        "gdsc_dose_response",
        "gdsc2_ic50",
        "gdsc2-ic50",
        "gdsc2_dataset",
    ]
    dose_response_path = find_file(
        RAW_DIR, dose_response_patterns, "Dose-response data"
    )

    # ── Search for cell line details / model annotation file ───────────────
    cell_lines_patterns = [
        "cell_lines_details",
        "cell_line_details",
        "model_annotation",
        "model_list",
    ]
    cell_lines_path = find_file(
        RAW_DIR, cell_lines_patterns, "Cell line details / Model annotation"
    )

    # ── Report what's missing ──────────────────────────────────────────────
    missing = []
    if dose_response_path is None:
        missing.append("Drug Sensitivity Data (GDSC2 dose-response)")
    if cell_lines_path is None:
        missing.append("Model Annotation (cell line details)")

    if missing:
        print(f"\n  ✗ Missing {len(missing)} file(s):")
        for m in missing:
            print(f"    • {m}")
        print(MANUAL_DOWNLOAD_INSTRUCTIONS.format(raw_dir=RAW_DIR))

        if dose_response_path is None:
            return None, cell_lines_path

    return dose_response_path, cell_lines_path


def load_datafile(path: Path) -> pd.DataFrame:
    """
    Auto-detect file format and load as DataFrame.
    Supports .xlsx, .csv, .tsv
    """
    suffix = path.suffix.lower()
    print(f"  Loading {path.name} (format: {suffix})...")

    if suffix == ".xlsx" or suffix == ".xls":
        return pd.read_excel(path)
    elif suffix == ".tsv":
        return pd.read_csv(path, sep="\t")
    else:  # default to CSV
        return pd.read_csv(path)


